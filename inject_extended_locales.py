def inject_keys(content, new_dict):
    for section, keys in new_dict.items():
        pattern = rf'({section}:\s*\{{)'
        replacement = r'\1'
        lines_to_add = []
        for k, v in keys.items():
            # escape double quotes
            v_escaped = v.replace('"', '\\"')
            lines_to_add.append(f'\n    {k}: "{v_escaped}",')
        addition = "".join(lines_to_add)
        content = re.sub(pattern, rf'\1{addition}', content)
    return content

